"""Convert art/ts101_home_assets.h, the source of truth, to the firmware's bitmaps: ts101_dog_home_assets.h/.cpp in mono_128x32.
The header has one uint32 per row with bit 31 on the left; the firmware has columns in pages of 8 rows with bit 0 on top.
The 3x5 font is not converted: dogFontTiny already has it, shared with other screens. This checks the labels of the home and soldering screens match."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'art', 'ts101_home_assets.h')
TARGET = os.path.join(HERE, '..', '..', 'source', 'Core', 'Threads', 'UI', 'drawing', 'mono_128x32', 'ts101_dog_home_assets')
HOME_LABELS = 'GESAMT SEIT START VORGÄNGE BOOSTS TOTAL SESSION RUNS NOCH ZEIT LEFT TIME SNBI BLEILOT BLEIFREI SNCU MASSE LEADED LEADFREE MASS EIGEN OWN W A S ° /'
HEADER_POSES = ['FRONT', 'EYES_LEFT', 'EYES_RIGHT', 'TURN_LEFT', 'TURN_RIGHT', 'COCK', 'UP', 'EARS_BACK', 'BLINK', 'TONGUE']
POSES = [p for p in HEADER_POSES if not p.startswith('EYES_')]  # the eyes alone differ too little from FRONT
ICONS = [('iconHomeSliders', 'TS101_ICON_SLIDERS', 9, 7), ('iconHomePlay', 'TS101_ICON_PLAY', 4, 7),
         ('iconHomeArrowDown', 'TS101_ARROW_DOWN', 5, 5), ('iconHomeArrowUp', 'TS101_ARROW_UP', 5, 5)]


def to_pages(rows, width):
    """Rows of a uint32 to the firmware's format; the height is padded to whole pages, which is what dogBlit takes"""
    pages = (len(rows) + 7) // 8
    out = []
    for page in range(pages):
        for x in range(width):
            byte = 0
            for bit in range(8):
                y = page * 8 + bit
                if y < len(rows) and (rows[y] >> (31 - x)) & 1:
                    byte |= 1 << bit
            out.append(byte)
    return out


def table(values, per=16):
    return ',\n'.join('    ' + ', '.join(f'0x{v:02X}' for v in values[i:i + per]) for i in range(0, len(values), per))


def read_array(text, name):
    match = re.search(name + r'\[\d+\]\s*=\s*\{(.*?)\};', text, re.S)
    return [int(v, 16) for v in re.findall(r'0x[0-9A-Fa-f]+', match.group(1))]


def check_font(text):
    """Every letter of the home screen's labels has the same rows in the header and in art/home.txt (dogFontTiny)"""
    header = {m[0]: [int(v) for v in m[1].split(',')] for m in re.findall(r'\{ "(.+?)", \{ ([\d, ]+) \} \}', text)}
    tiny = {}
    for line in open(os.path.join(HERE, 'art', 'home.txt'), encoding='utf8'):
        if line.startswith('tiny '):
            _, char, *rows = line.split()
            tiny[char] = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]
    for char in set(HOME_LABELS) - {' '}:
        if header.get(char) is None or tiny.get(char) != header[char]:
            sys.exit(f'{char}: the 3x5 font in the header differs from dogFontTiny')


def main():
    text = open(SOURCE, encoding='utf8').read()
    check_font(text)
    block = re.search(r'TS101_DOG_HEADS\[10\]\[32\]\s*=\s*\{(.*?)\n\};', text, re.S).group(1)
    heads = [int(v, 16) for v in re.findall(r'0x[0-9A-Fa-f]{8}', block)]
    assert len(heads) == 10 * 32, len(heads)
    hdr = ['// Generated by scripts/ts101_dog/make_home_assets.py from art/ts101_home_assets.h - do not edit', '#ifndef TS101_DOG_HOME_ASSETS_H_', '#define TS101_DOG_HOME_ASSETS_H_', '#include <stdint.h>', '',
           'enum DogPose : uint8_t {' + ', '.join(f'DOG_POSE_{p}' for p in POSES) + '};', '#define DOG_POSE_SIZE 32 // width and height', f'extern const uint8_t dogPoses[{len(POSES)}][128];']
    src = ['// Generated by scripts/ts101_dog/make_home_assets.py from art/ts101_home_assets.h - do not edit', '#include "configuration.h"', '#ifdef TS101_DOG_UI', '#include "ts101_dog_home_assets.h"', '',
           f'const uint8_t dogPoses[{len(POSES)}][128] = {{']
    for pose in POSES:
        i = HEADER_POSES.index(pose)
        src += [f'  // {pose}', '  {', table(to_pages(heads[i * 32:(i + 1) * 32], 32)), '  },']
    src += ['};', '']
    for name, source, width, height in ICONS:
        rows = read_array(text, source)
        assert len(rows) == height, source
        data = to_pages(rows, width)
        hdr.append(f'extern const uint8_t {name}[{len(data)}]; // {width}x{height}')
        src += [f'const uint8_t {name}[{len(data)}] = {{', table(data), '};', '']
    hdr += ['', '#endif // TS101_DOG_HOME_ASSETS_H_', '']
    src += ['#endif', '']
    open(TARGET + '.h', 'w', encoding='utf8').write('\n'.join(hdr))
    open(TARGET + '.cpp', 'w', encoding='utf8').write('\n'.join(src))


if __name__ == '__main__':
    main()
