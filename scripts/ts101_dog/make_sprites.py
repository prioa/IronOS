"""Generate source/Core/Threads/UI/drawing/mono_128x32/ts101_dog_sprites.h from the drawings in gsd32.py."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image
from gsd32 import lying

ZZZ_STEPS = [  # sleep "z Z Z" animation, 24x8, one page tall
    [(0, 4, 'z')],
    [(0, 4, 'z'), (7, 2, 'Z')],
    [(0, 4, 'z'), (7, 2, 'Z'), (15, 0, 'ZZ')],
]
GLYPHS = {
    'z':  ["####", "..#.", ".#..", "####"],
    'Z':  ["#####", "...#.", "..#..", ".#...", "#####"],
    'ZZ': ["#######", ".....#.", "....#..", "...#...", "..#....", ".#.....", "#######"],
}

def zzz(step):
    img = Image.new('L', (24, 8), 0)
    for x, y, g in ZZZ_STEPS[step]:
        for dy, row in enumerate(GLYPHS[g]):
            for dx, c in enumerate(row):
                if c == '#': img.putpixel((x + dx, y + dy), 255)
    return img

def columns(img):
    px = img.load(); out = []
    for page in range(img.height // 8):
        for x in range(img.width):
            b = 0
            for bit in range(8):
                if px[x, page * 8 + bit]: b |= 1 << bit
            out.append(b)
    return out

def c_array(name, img):
    data = columns(img)
    lines = [', '.join(f'0x{b:02X}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return (f'// {img.width}x{img.height}\n'
            f'static const uint8_t {name}[] = {{\n  ' + ',\n  '.join(lines) + ',\n};\n')

if __name__ == '__main__':
    out = ['// Generated by scripts/ts101_dog/make_sprites.py - do not edit',
           '#ifndef TS101_DOG_SPRITES_H_', '#define TS101_DOG_SPRITES_H_', '#include <stdint.h>', '',
           '#define DOG_LYING_WIDTH  72', '#define DOG_LYING_HEIGHT 24', '#define DOG_ZZZ_WIDTH    24',
           f'#define DOG_ZZZ_STEPS    {len(ZZZ_STEPS)}', '']
    out.append(c_array('dogLying', lying()))
    for i in range(len(ZZZ_STEPS)):
        out.append(c_array(f'dogZzz{i}', zzz(i)))
    out.append('static const uint8_t *const dogZzz[DOG_ZZZ_STEPS] = {' + ', '.join(f'dogZzz{i}' for i in range(len(ZZZ_STEPS))) + '};')
    out += ['', '#endif // TS101_DOG_SPRITES_H_', '']
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'source', 'Core', 'Threads', 'UI', 'drawing', 'mono_128x32', 'ts101_dog_sprites.h')
    open(target, 'w').write('\n'.join(out))
    print('wrote', os.path.normpath(target))
